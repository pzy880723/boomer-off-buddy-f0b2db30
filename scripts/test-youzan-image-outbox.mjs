import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";
const db = new PGlite();
const id = n => `00000000-0000-0000-0000-${String(n).padStart(12, "0")}`;
try {
  await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
    CREATE TABLE inv_skus(id uuid PRIMARY KEY, status text DEFAULT 'active', sku_scope text DEFAULT 'custom',
      barcode text DEFAULT '20000001', image_paths text[] DEFAULT '{}', image_url text);
    CREATE TABLE youzan_shops(id uuid PRIMARY KEY, kdt_id bigint, role text, status text DEFAULT 'active');
    CREATE TABLE inv_locations(id uuid PRIMARY KEY, shop_id uuid, is_active boolean DEFAULT true);
    CREATE TABLE inv_stocks(sku_id uuid,location_id uuid,qty int);
    CREATE TABLE sku_youzan_links(sku_id uuid,shop_id uuid,role text,status text DEFAULT 'linked',
      sync_stock boolean DEFAULT true,yz_item_id bigint,PRIMARY KEY(sku_id,shop_id));
    CREATE TABLE sku_channel_listings(sku_id uuid,shop_id uuid,channel text DEFAULT 'youzan_branch_offline',
      listing_status text DEFAULT 'published',external_item_id text,PRIMARY KEY(sku_id,shop_id));`);
  await db.exec(await readFile(new URL("../supabase/migrations/20260927190000_youzan_image_refresh.sql", import.meta.url), "utf8"));
  await db.query("INSERT INTO inv_skus(id,image_paths) VALUES($1,ARRAY['sku-raw/a'])", [id(1)]);
  await db.query("INSERT INTO youzan_shops(id,kdt_id,role) VALUES($1,10,'branch'),($2,20,'branch'),($3,30,'hq')", [id(2),id(3),id(4)]);
  await db.query("INSERT INTO inv_locations(id,shop_id) VALUES($1,$2)", [id(5),id(2)]);
  await db.query("INSERT INTO inv_stocks VALUES($1,$2,1)", [id(1),id(5)]);
  await db.query("INSERT INTO sku_youzan_links(sku_id,shop_id,role,yz_item_id) VALUES($1,$2,'branch_stock',200),($1,$3,'hq_spu',100)", [id(1),id(2),id(4)]);
  await db.query("INSERT INTO sku_channel_listings(sku_id,shop_id,external_item_id) VALUES($1,$2,'200')", [id(1),id(2)]);
  const queue = () => db.query("SELECT * FROM youzan_image_refresh_outbox").then(r=>r.rows);
  const claim = () => db.query("SELECT * FROM youzan_image_refresh_claim(2)").then(r=>r.rows);
  const snapshot = row => db.query("SELECT youzan_image_refresh_snapshot($1,$2,$3) AS v", [row.id,row.claim_token,row.revision]).then(r=>r.rows[0].v);
  const finish = (row,error=null) => db.query("SELECT youzan_image_refresh_finish($1,$2,$3,$4) AS v", [row.id,row.claim_token,row.revision,error]).then(r=>r.rows[0].v);
  assert.equal((await queue()).length,1);
  const [first] = await claim();
  assert.equal((await claim()).length,0,"only one active claim");
  assert.equal((await snapshot(first)).hq_spu_id,100);
  await db.query("UPDATE inv_skus SET image_paths=ARRAY['sku-listing/a','sku-listing/b'] WHERE id=$1",[id(1)]);
  assert.equal(await snapshot(first),null,"old revision fenced before remote write");
  assert.equal(await finish(first),"queued","old completion cannot acknowledge new images");
  const [latest] = await claim();
  assert.deepEqual((await snapshot(latest)).image_paths,["sku-listing/a","sku-listing/b"]);
  assert.equal(await finish(latest),"succeeded");
  const doneRevision=(await queue())[0].revision;
  assert.equal(await finish(latest),"duplicate");
  assert.equal((await queue())[0].revision,doneRevision,"completion replay is idempotent");
  await db.query("UPDATE inv_skus SET image_paths=image_paths WHERE id=$1",[id(1)]);
  assert.equal((await queue())[0].status,"succeeded","unchanged images do not requeue");
  await db.query("UPDATE sku_channel_listings SET external_item_id=external_item_id WHERE sku_id=$1",[id(1)]);
  const [publish] = await claim();
  assert.ok(publish,"late publish must force latest refresh even with unchanged images");
  await db.exec("UPDATE youzan_image_refresh_outbox SET lease_until=now()-interval '1 second'");
  const [reclaimed] = await claim();
  assert.notEqual(reclaimed.claim_token,publish.claim_token);
  assert.equal(await finish(publish),"stale","stale claim cannot finish successor");
  assert.equal(await finish(reclaimed),"queued","late stale writer forces convergence retry");
  const [again] = await claim();
  assert.equal(await finish(again,"upload_failed"),"retryable_failed");
  assert.equal((await claim()).length,0,"backoff is honored");
  await db.exec("UPDATE youzan_image_refresh_outbox SET next_run_at=now()");
  const [deleted] = await claim();
  await db.query("UPDATE inv_skus SET status='archived' WHERE id=$1",[id(1)]);
  assert.equal(await snapshot(deleted),null,"archived SKU never gets remote image writes");
  assert.equal(await finish(deleted),"cancelled");
  assert.equal((await queue())[0].last_error,"image_target_not_eligible");
  await db.query("UPDATE inv_skus SET status='active',image_paths=ARRAY['sku-listing/c'] WHERE id=$1",[id(1)]);
  await db.query("UPDATE sku_channel_listings SET listing_status='delisted' WHERE sku_id=$1",[id(1)]);
  const [delisted] = await claim();
  assert.equal(await snapshot(delisted),null);
  assert.equal(await finish(delisted),"cancelled");
  assert.equal((await queue()).length,1,"no task for another branch");
  assert.equal((await db.query("SELECT qty FROM inv_stocks")).rows[0].qty,1);
  await db.exec("SET ROLE authenticated");
  await assert.rejects(db.query("SELECT youzan_image_refresh_enqueue($1,$2)",[id(1),id(2)]),/permission denied/);
  console.log("PASS atomic enqueue, revisions, single claim, lease recovery, late publish, retries, archive/delist, shop isolation, no stock writes, RPC permissions");
} finally { await db.close(); }
